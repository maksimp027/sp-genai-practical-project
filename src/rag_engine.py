"""
Multimodal Retrieval-Augmented Generation (RAG) Engine.
Integrates vector retrieval with multimodal LLM generation (Gemini, Ollama, OpenAI),
supporting cross-modal context grounding and citations.
"""

import logging
import os
import time
from pathlib import Path
from typing import Any, Dict, List, Optional

from src.indexer import MultimodalIndex

logger = logging.getLogger(__name__)

SYSTEM_PROMPT = """You are an expert AI news assistant summarizing articles from DeepLearning.AI's 'The Batch'.
Your goal is to answer the user's question accurately, concisely, and factually based ONLY on the provided retrieved context.

Guidelines:
1. Base your answer strictly on the provided context. Do not invent facts or dates.
2. Cite the source articles in your answer using bracketed numbers like [1], [2] corresponding to the sources listed.
3. If relevant images or figures are provided, reference them naturally in your explanation (e.g. 'As shown in the architecture figure for [1]...').
4. If the context does not contain enough information to answer completely, state clearly what is known and what is missing.
5. Provide a well-structured response (summary, key details, implications).
"""


class RAGEngine:
    """Multimodal RAG orchestrator combining ChromaDB retrieval with LLM synthesis."""

    def __init__(
        self,
        index: Optional[MultimodalIndex] = None,
        db_path: Path = Path("data/chroma_db"),
        gemini_api_key: Optional[str] = None,
        openai_api_key: Optional[str] = None,
        ollama_model: str = "qwen2.5-coder:7b",
        ollama_base_url: str = "http://localhost:11434",
    ):
        self.index = index or MultimodalIndex(db_path=db_path)
        self.gemini_api_key = gemini_api_key or os.getenv("GEMINI_API_KEY")
        self.openai_api_key = openai_api_key or os.getenv("OPENAI_API_KEY")
        self.ollama_model = ollama_model
        self.ollama_base_url = ollama_base_url.rstrip("/")

    def _build_context_prompt(self, retrieval_result: Dict[str, Any]) -> str:
        """Construct formatted context text with source numbering for the LLM."""
        articles = retrieval_result.get("articles", [])
        if not articles:
            return "No relevant articles were found in the database."

        context_blocks = []
        for i, art in enumerate(articles, start=1):
            chunks_text = "\n".join(art.get("chunks", []))
            tags_str = art.get("tags", "")
            img_info = f"Associated images: {len(art.get('local_images', []))}"

            block = (
                f"[Source {i}]\n"
                f"Title: {art.get('title')}\n"
                f"Date: {art.get('date', 'Unknown')}\n"
                f"URL: {art.get('url', '')}\n"
                f"Tags: {tags_str}\n"
                f"{img_info}\n"
                f"Content:\n{chunks_text}\n"
            )
            context_blocks.append(block)

        return "\n---\n".join(context_blocks)

    def _generate_with_gemini(
        self, prompt: str, image_paths: List[str], api_key: str, model_name: str = "gemini-2.5-flash"
    ) -> str:
        """Generate answer using Google Gemini with multimodal vision support."""
        from google import genai
        from google.genai import types
        from PIL import Image

        client = genai.Client(api_key=api_key)

        contents: List[Any] = [prompt]
        # Attach up to 2 top retrieved images if they exist
        for img_p in image_paths[:2]:
            try:
                if Path(img_p).exists():
                    img = Image.open(img_p)
                    contents.append(img)
            except Exception as e:
                logger.warning("Could not open image %s for Gemini: %s", img_p, e)

        response = client.models.generate_content(
            model=model_name,
            contents=contents,
            config=types.GenerateContentConfig(
                system_instruction=SYSTEM_PROMPT,
                temperature=0.2,
                max_output_tokens=1000,
            ),
        )
        return response.text or "No response generated by Gemini."

    def _generate_with_ollama(self, prompt: str, model: str) -> str:
        """Generate answer using local Ollama instance."""
        import json
        import urllib.request

        payload = {
            "model": model,
            "prompt": f"{SYSTEM_PROMPT}\n\n{prompt}",
            "stream": False,
            "options": {"temperature": 0.2, "num_predict": 800},
        }

        url = f"{self.ollama_base_url}/api/generate"
        req = urllib.request.Request(
            url,
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json"},
        )
        with urllib.request.urlopen(req, timeout=45) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            return data.get("response", "No response returned by Ollama.")

    def _generate_with_openai(self, prompt: str, api_key: str, model_name: str = "gpt-4o-mini") -> str:
        """Generate answer using OpenAI API."""
        from openai import OpenAI

        client = OpenAI(api_key=api_key)
        response = client.chat.completions.create(
            model=model_name,
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": prompt},
            ],
            temperature=0.2,
            max_tokens=800,
        )
        return response.choices[0].message.content or ""

    def _generate_extractive_fallback(self, query: str, retrieval_result: Dict[str, Any]) -> str:
        """
        Graceful local fallback when no LLM API key or Ollama daemon is accessible.
        Synthesizes an informative answer from the top retrieved chunks.
        """
        articles = retrieval_result.get("articles", [])
        if not articles:
            return "No matching articles found in The Batch database for this query."

        top_art = articles[0]
        answer_parts = [
            f"Based on retrieved articles from The Batch regarding **'{query}'**:\n",
            f"### Primary Finding ([1] {top_art['title']})",
        ]

        # Extract top 2 sentences
        chunks = top_art.get("chunks", [""])
        body = chunks[0].replace(f"Title: {top_art['title']}\n\n", "")
        sentences = [s.strip() for s in body.split(". ") if len(s.strip()) > 30]
        if sentences:
            answer_parts.append(". ".join(sentences[:3]) + ".")

        if len(articles) > 1:
            second_art = articles[1]
            answer_parts.append(f"\n### Related Developments ([2] {second_art['title']})")
            sec_chunks = second_art.get("chunks", [""])
            sec_body = sec_chunks[0].replace(f"Title: {second_art['title']}\n\n", "")
            sec_sentences = [s.strip() for s in sec_body.split(". ") if len(s.strip()) > 30]
            if sec_sentences:
                answer_parts.append(". ".join(sec_sentences[:2]) + ".")

        answer_parts.append("\n\n*Note: Running in local extractive mode. Configure a Gemini, Ollama, or OpenAI key in the sidebar for generative synthesis.*")
        return "\n".join(answer_parts)

    def answer_query(
        self,
        query: str,
        top_k: int = 4,
        backend: str = "auto",  # 'gemini', 'ollama', 'openai', 'extractive', 'auto'
        gemini_model: str = "gemini-2.5-flash",
        ollama_model: Optional[str] = None,
        openai_model: str = "gpt-4o-mini",
    ) -> Dict[str, Any]:
        """
        End-to-end multimodal RAG pipeline:
        Retrieves relevant documents and images, then calls selected LLM generator.
        """
        t0 = time.time()
        retrieval_data = self.index.search_multimodal(query, top_k=top_k)
        retrieval_duration = round(time.time() - t0, 3)

        context_str = self._build_context_prompt(retrieval_data)
        full_user_prompt = f"User Question: {query}\n\nRetrieved Context:\n{context_str}\n\nPlease provide a clear answer with citations to the numbered sources."

        # Collect image paths for multimodal generation
        gallery_images = retrieval_data.get("gallery_images", [])
        image_paths = [img["local_path"] for img in gallery_images if img.get("local_path")]

        # Determine backend
        chosen_backend = backend
        active_model = ""
        error_msg = None

        if chosen_backend == "auto":
            if self.gemini_api_key:
                chosen_backend = "gemini"
            elif self.openai_api_key:
                chosen_backend = "openai"
            else:
                # Test Ollama connectivity
                try:
                    import urllib.request
                    req = urllib.request.Request(f"{self.ollama_base_url}/api/tags", timeout=1.0)
                    with urllib.request.urlopen(req) as resp:
                        if resp.status == 200:
                            chosen_backend = "ollama"
                        else:
                            chosen_backend = "extractive"
                except Exception:
                    chosen_backend = "extractive"

        t_gen = time.time()
        answer = ""

        try:
            if chosen_backend == "gemini":
                api_key = self.gemini_api_key or os.getenv("GEMINI_API_KEY", "")
                if not api_key:
                    raise ValueError("Gemini API key is not set.")
                active_model = gemini_model
                answer = self._generate_with_gemini(
                    full_user_prompt, image_paths, api_key=api_key, model_name=gemini_model
                )

            elif chosen_backend == "ollama":
                model_to_use = ollama_model or self.ollama_model
                active_model = f"Ollama ({model_to_use})"
                answer = self._generate_with_ollama(full_user_prompt, model=model_to_use)

            elif chosen_backend == "openai":
                api_key = self.openai_api_key or os.getenv("OPENAI_API_KEY", "")
                if not api_key:
                    raise ValueError("OpenAI API key is not set.")
                active_model = openai_model
                answer = self._generate_with_openai(full_user_prompt, api_key=api_key, model_name=openai_model)

            else:
                active_model = "Local Extractive Synthesizer"
                answer = self._generate_extractive_fallback(query, retrieval_data)

        except Exception as e:
            logger.warning("Generation with %s failed (%s), falling back to extractive summary.", chosen_backend, e)
            error_msg = str(e)
            active_model = f"Fallback ({chosen_backend} failed)"
            answer = self._generate_extractive_fallback(query, retrieval_data)

        generation_duration = round(time.time() - t_gen, 3)

        return {
            "query": query,
            "answer": answer,
            "backend": chosen_backend,
            "model_used": active_model,
            "error": error_msg,
            "articles": retrieval_data.get("articles", []),
            "gallery_images": gallery_images,
            "text_hits": retrieval_data.get("text_hits", []),
            "retrieval_time": retrieval_duration,
            "generation_time": generation_duration,
        }
